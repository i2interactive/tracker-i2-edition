const uint8_t* columns(char c)
{
    if (c >= 'a' && c <= 'z')
    {
        c = (char)(c - 'a' + 'A');
    }
    uint8_t u = (uint8_t)c;
    if (u < kFirstChar || u >= kFirstChar + kGlyphs)
    {
        u = kFirstChar;
    }
    return kFont[u - kFirstChar];
}

void renderGlyph(uint8_t size, char c, uint8_t* out)
{
    const uint8_t pitch = kPitch[size], lit = kLit[size];
    const uint8_t st = stride(size), h = cellH(size);
    memset(out, 0, (size_t)st * h);
    const uint8_t* col = columns(c);
    for (uint8_t cx = 0; cx < 5; cx++)
    {
        for (uint8_t cy = 0; cy < 7; cy++)
        {
            if (!(col[cx] & (1u << cy)))
            {
                continue;
            }
            for (uint8_t py = 0; py < lit; py++)
            {
                for (uint8_t px = 0; px < lit; px++)
                {
                    uint16_t x = (uint16_t)(cx * pitch + px);
                    uint16_t y = (uint16_t)(cy * pitch + py);
                    out[y * st + (x >> 3)] |= (uint8_t)(0x80u >> (x & 7));
                }
            }
        }
    }
}

uint32_t buildFont(uint8_t size, uint8_t* out)
{
    const uint32_t glyphBytes = (uint32_t)stride(size) * cellH(size);
    memset(out, 0, kMetricSize);
    for (uint8_t c = kFirstChar; c < kFirstChar + kGlyphs; c++)
    {
        out[c] = cellW(size); // advance per character
    }
    const uint32_t fields[5] = { 1 /* L1 */, stride(size), cellW(size), cellH(size), kAddress[size] + kMetricSize };
    for (uint8_t f = 0; f < 5; f++)
    {
        for (uint8_t b = 0; b < 4; b++)
        {
            out[128 + f * 4 + b] = (uint8_t)(fields[f] >> (8 * b));
        }
    }
    for (uint8_t g = 0; g < kGlyphs; g++)
    {
        renderGlyph(size, (char)(kFirstChar + g), out + kMetricSize + g * glyphBytes);
    }
    return kMetricSize + kGlyphs * glyphBytes;
}

