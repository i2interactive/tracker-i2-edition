"""Writes font_metrics.h: per-character advance widths for the host stand-in fonts."""
from pathlib import Path

from PIL import ImageFont

from fonts import FONTS

out = ["// generated by gen_metrics.py", "#pragma once", "#include <stdint.h>", ""]
ids = sorted(FONTS)
out.append("static const uint8_t kHostFontIds[] = {" + ", ".join(str(i) for i in ids) + "};")
out.append("static const uint8_t kHostFontHeight[] = {" + ", ".join(str(FONTS[i][2]) for i in ids) + "};")
out.append("static const uint8_t kHostAdvance[][95] = {")
for i in ids:
    path, size, _ = FONTS[i]
    f = ImageFont.truetype(path, size)
    row = [str(max(1, round(f.getlength(chr(c))))) for c in range(32, 127)]
    out.append("    {" + ", ".join(row) + "},")
out.append("};")
Path(__file__).with_name("font_metrics.h").write_text("\n".join(out) + "\n")
print("ok")
