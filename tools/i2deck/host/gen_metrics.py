"""Writes font_metrics.h: per-character advance widths for the host harness.
Fonts 0-4 come from the firmware's own font tables (exact); the ROM fonts
from the stand-in TTFs. Needs Pillow and fonts-liberation / fonts-dejavu."""
import re
from pathlib import Path

from PIL import ImageFont

from fonts import FIRMWARE, FONTS

FONT_DIR = Path(__file__).resolve().parents[3] / "core/libs/fonts"


def firmware_widths(name):
    """The FT81x metric block starts the font data: 128 width bytes, char 0-127."""
    src = (FONT_DIR / (name + "_L4.cpp")).read_text()
    body = src[src.index("= {") + 3:]
    data = []
    for v, c in re.findall(r"\{(\d+),\s*(\d+)\}", body):
        data += [int(v)] * int(c)
        if len(data) >= 128:
            break
    return [max(1, data[c]) for c in range(32, 127)]


out = ["// generated by gen_metrics.py", "#pragma once", "#include <stdint.h>", ""]
ids = sorted(FONTS)
out.append("static const uint8_t kHostFontIds[] = {" + ", ".join(str(i) for i in ids) + "};")
out.append("static const uint8_t kHostFontHeight[] = {" + ", ".join(str(FONTS[i][2]) for i in ids) + "};")
out.append("static const uint8_t kHostAdvance[][95] = {")
for i in ids:
    if i in FIRMWARE:
        row = firmware_widths(FIRMWARE[i])
    else:
        path, size, _ = FONTS[i]
        f = ImageFont.truetype(path, size)
        row = [max(1, round(f.getlength(chr(c)))) for c in range(32, 127)]
    out.append("    {" + ", ".join(str(v) for v in row) + "},")
out.append("};")
Path(__file__).with_name("font_metrics.h").write_text("\n".join(out) + "\n")
print("ok")
